/**
 * Auto-scaffold TypeScript/JavaScript project config for Brain code indexing.
 * Writes workspace/.minnow/brain-jsconfig.json when no ts/js config exists.
 */

import { execFile } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { promisify } from 'node:util';
import { rgPath } from '@vscode/ripgrep';

const execFileAsync = promisify(execFile);

/** Relative path of the Minnow-managed jsconfig inside a workspace. */
export const BRAIN_JS_CONFIG_REL = '.minnow/brain-jsconfig.json';

/** Marker key inside the scaffold file — used to detect Minnow-owned config. */
export const BRAIN_JS_CONFIG_MARKER = '_minnow';

/** Ripgrep args shared by workspace scans. */
const RG_SKIP_GLOBS = ['!**/node_modules/**', '!**/.git/**', '!**/dist/**', '!**/build/**'];

/**
 * Run ripgrep --files with glob filters under a workspace root.
 * @param {string} root
 * @param {string[]} includeGlobs
 */
async function rgListFiles(root, includeGlobs) {
  const args = ['--files', '--no-messages', ...RG_SKIP_GLOBS.flatMap((g) => ['--glob', g])];
  for (const glob of includeGlobs) {
    args.push('--glob', glob);
  }
  args.push(root);
  try {
    const { stdout } = await execFileAsync(rgPath, args, {
      cwd: root,
      maxBuffer: 4 * 1024 * 1024,
      windowsHide: true,
    });
    return stdout
      .split(/\r?\n/)
      .map((line) => line.trim().replace(/\\/g, '/'))
      .filter(Boolean);
  } catch (err) {
    const code = err && typeof err === 'object' ? err.code : undefined;
    if (code === 1) return [];
    throw err;
  }
}

/**
 * Whether the workspace already has a TypeScript/JavaScript project config.
 * @param {string} root
 */
export async function workspaceHasTypeScriptProjectConfig(root) {
  const hits = await rgListFiles(root, ['tsconfig.json', 'jsconfig.json', 'tsconfig.*.json']);
  return hits.length > 0;
}

/**
 * Whether the workspace contains indexable JS/TS source files.
 * @param {string} root
 */
export async function workspaceHasJsTsSources(root) {
  const hits = await rgListFiles(root, ['*.{ts,tsx,js,jsx,mjs,cjs,mts,cts}']);
  return hits.length > 0;
}

/**
 * Build the scaffold jsconfig payload (lives in .minnow/ and includes parent tree).
 */
export function buildBrainJsConfig() {
  return {
    [BRAIN_JS_CONFIG_MARKER]:
      'Auto-generated by Minnow for Brain code indexing. Safe to delete; Minnow recreates on reindex when needed.',
    compilerOptions: {
      module: 'ESNext',
      target: 'ES2022',
      moduleResolution: 'bundler',
      checkJs: true,
      allowJs: true,
      noEmit: true,
      skipLibCheck: true,
      maxNodeModuleJsDepth: 2,
    },
    include: ['../**/*'],
    exclude: ['../node_modules', '../dist', '../build', '../.git'],
  };
}

/**
 * Ensure a jsconfig exists for LSP indexing when the workspace has JS/TS but no project file.
 * @param {string} root
 * @param {{ enabled?: boolean }} [opts]
 * @returns {Promise<{ created: boolean, path?: string, skipped?: boolean, reason?: string }>}
 */
export async function ensureBrainIndexProjectConfig(root, opts = {}) {
  if (opts.enabled === false) {
    return { created: false, skipped: true, reason: 'disabled' };
  }

  const normalizedRoot = path.resolve(root);
  const scaffoldAbs = path.join(normalizedRoot, BRAIN_JS_CONFIG_REL);

  if (await workspaceHasTypeScriptProjectConfig(normalizedRoot)) {
    return { created: false, skipped: true, reason: 'project-config-exists' };
  }

  if (!(await workspaceHasJsTsSources(normalizedRoot))) {
    return { created: false, skipped: true, reason: 'no-js-ts-sources' };
  }

  try {
    const existing = await fs.readFile(scaffoldAbs, 'utf8');
    try {
      const parsed = JSON.parse(existing);
      if (parsed && typeof parsed === 'object' && BRAIN_JS_CONFIG_MARKER in parsed) {
        return {
          created: false,
          skipped: true,
          reason: 'scaffold-exists',
          path: BRAIN_JS_CONFIG_REL,
        };
      }
    } catch {
      /* non-JSON or invalid — treat as user-owned */
    }
    return { created: false, skipped: true, reason: 'custom-file-present', path: BRAIN_JS_CONFIG_REL };
  } catch {
    /* scaffold missing — create below */
  }

  await fs.mkdir(path.dirname(scaffoldAbs), { recursive: true });
  const body = buildBrainJsConfig();
  await fs.writeFile(scaffoldAbs, `${JSON.stringify(body, null, 2)}\n`, 'utf8');
  return { created: true, path: BRAIN_JS_CONFIG_REL };
}
